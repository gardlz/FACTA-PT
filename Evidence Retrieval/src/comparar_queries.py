"""Evaluates the query strategies against the reference evidence annotation.

Compares the complete claim, the claim span and the questions generated by 14 models under
Single-search top-5, RRF top-5 and Matched retrieval volume, with Relevant/Decisive Macro and
Micro Recall, DCSC and Docs/span. A reissue of a reference document counts as a hit.
"""

import argparse
import csv
import json
import os
import sys
from collections import defaultdict
from pathlib import Path

RETRIEVAL = Path(__file__).resolve().parent            # src/
REPO = RETRIEVAL.parent                                # stage folder
sys.path.insert(0, str(RETRIEVAL))
import dedup_versions as dedup  # noqa: E402
from comum import CLEVER_JSON, iter_claim_spans, ler_clever  # noqa: E402

EXPORT = REPO / "data/export_evidencias/evidencias.csv"
DATASET = CLEVER_JSON
SAIDA = REPO / "outputs/comparacao_queries.md"
# Condition of evidencias.csv that is not evaluated (the CLEVER gold questions). Its documents
# still take part in the reissue equivalence.
REFERENCIA = "pergunta_gold"
CORTE = 5

CONFIGURACOES = (
    ("primeira_pergunta", "Single-search top-5"),
    ("rrf", "RRF top-5"),
    ("orcamento_igual", "Matched retrieval volume"),
)

# Condition ids of evidencias.csv -> names used in the dissertation.
NOMES = {
    "claim_frase": "Claim", "claim_span": "Claim span",
    "FT_ptt5_large": "PTT5 Large", "FT_ptt5v2_large": "PTT5-v2 Large", "FT_ptt5v2_3b": "PTT5-v2 3B",
    "FT_mt0_large": "mT0 Large", "FT_mt5_xl": "mT5 XL", "FT_mt0_xxl": "mT0 XXL",
    "FT_tucano_1b1": "Tucano-1b1-Instruct", "FT_llama32_1b": "Llama 3.2-1B-Instruct",
    "FT_gloria_1b3": "GlórIA-1.3B", "FT_bode_7b": "Bode-7B-Alpaca",
    "FT_llama_8b": "Llama 3.1-8B-Instruct", "FT_gervasio_8b": "Gervásio-8B PT-PT",
    "FT_amalia_9b": "AMALIA-9B-0626-DPO", "FT_mistral_nemo": "Mistral NeMo-12B-Instruct",
}


def indice_da_pergunta(question_id):
    sufixo = question_id.rsplit("__q", 1)[-1] if "__q" in question_id else ""
    return int(sufixo) if sufixo.isdigit() else 1


def ler_export():
    """{condition: {span_id: {question_id: [(rank, doc_id)]}}}, each search sorted by rank."""
    dados = defaultdict(lambda: defaultdict(lambda: defaultdict(list)))
    with open(EXPORT, encoding="utf-8") as f:
        for r in csv.DictReader(f):
            dados[r["condicao"]][r["span_id"]][r["question_id"]].append(
                (int(r["rank"]), str(r["doc_id"])))
    for condicao in dados.values():
        for span in condicao.values():
            for pesquisa in span.values():
                pesquisa.sort()
    return dados


def ler_gold(spans_do_export):
    """{span_id: {"decisivo", "relevante", "Supported", "Refuted": sets of doc_id}}, from the
    retrieved documents annotated in CLEVER."""
    gold = defaultdict(lambda: {"decisivo": set(), "relevante": set(),
                                "Supported": set(), "Refuted": set()})
    for _documento, _item, span_id, span in sorted(iter_claim_spans(ler_clever(DATASET)),
                                                   key=lambda x: x[2]):
        if span_id not in spans_do_export:
            continue
        for doc in span["retrieved_documents"]:
            if doc["relation"] in ("Supported", "Refuted"):
                gold[span_id]["decisivo"].add(doc["lusa_doc_id"])
                gold[span_id][doc["relation"]].add(doc["lusa_doc_id"])
            if doc["relevant"]:
                gold[span_id]["relevante"].add(doc["lusa_doc_id"])
    return gold


def ler_json(caminho):
    """Read a JSON file."""
    return json.loads(caminho.read_text(encoding="utf-8"))


def equivalencias(doc_ids):
    """{doc_id: key}, the same key for reissues of the same dispatch (cached documents only)."""
    documentos, chave = {}, {}
    for doc_id in doc_ids:
        caminho = REPO / f"outputs/lusa_docs/{doc_id}.json"
        if caminho.exists():
            documentos[doc_id] = ler_json(caminho)
    for grupo in dedup.agrupar_versoes(list(documentos.values())):
        canonica = sorted(str(x) for x in grupo)[0]
        for doc_id in grupo:
            chave[str(doc_id)] = canonica
    return {d: chave.get(d, d) for d in doc_ids}


K_RRF = 60

# 20-deep rankings of the two single-search conditions (evidencias.csv keeps only the top-5).
FUNDO_DE = {"claim_frase": REPO / "outputs/lusa_top20_frase",
            "claim_span": REPO / "outputs/lusa_top20_claim"}
FUNDO = {}          # {condition: {span_id: [doc_id, ...]}}, filled by preparar_fundo
ORCAMENTO = {}      # {span_id: B_i}


_FUNDO_BRUTO = {}


def ler_fundo_bruto():
    """{condition: {span_id: [doc_id, ...]}} of the 20-deep rankings, read once."""
    if _FUNDO_BRUTO:
        return _FUNDO_BRUTO
    for condicao, pasta in FUNDO_DE.items():
        if not pasta.is_dir():
            continue
        registos = {}
        for caminho in pasta.glob("*.json"):
            registo = ler_json(caminho)
            registos[registo["span_id"]] = [str(x["doc_id"]) for x in registo["results"]]
        _FUNDO_BRUTO[condicao] = registos
    return _FUNDO_BRUTO


def preparar_fundo(dados, chave):
    """Matched retrieval volume: B_i per span and the deep lists of the claim and claim span.

    B_i: median over the 14 generated-question conditions of the distinct doc_ids returned for
    span i (half to even), at least 5. Deep list: the stored top-5, which must be in the
    20-deep ranking, then the rest of that ranking without repeated news items.
    """
    modelos = [c for c in dados if c.startswith("FT_")]
    spans = sorted({s for c in modelos for s in dados[c]})
    for span_id in spans:
        contagens = sorted(len(lista(dados[c].get(span_id, {}), "realidade")) for c in modelos)
        meio = len(contagens) // 2
        mediana = (contagens[meio] if len(contagens) % 2
                   else (contagens[meio - 1] + contagens[meio]) / 2)
        ORCAMENTO[span_id] = max(int(round(mediana)), CORTE)

    for condicao, pasta in FUNDO_DE.items():
        if condicao not in dados:
            continue
        if not pasta.is_dir():
            modo = "frase" if condicao == "claim_frase" else "claim"
            sys.exit(
                f"Falta {pasta} — é lá que está o ranking fundo da condição `{condicao}`.\n"
                f"  python src/retrieve_lusa.py --query {modo} \\\n"
                f"      --output-dir {pasta.relative_to(REPO)} --size 20 --overfetch 2\n"
                f"Sem ela a Matched retrieval volume não se pode calcular: o export só tem 5 "
                f"documentos.")
        bruto = ler_fundo_bruto().get(condicao, {})
        fundo, maus = {}, []
        for span_id, pesquisas in dados[condicao].items():
            topo = lista(pesquisas, "realidade")
            resto = bruto.get(span_id, [])
            vistos = {chave.get(d, d) for d in topo}
            if not vistos <= {chave.get(d, d) for d in resto}:
                maus.append(span_id)
            fundo[span_id] = topo + [d for d in resto
                                     if chave.get(d, d) not in vistos
                                     and not vistos.add(chave.get(d, d))]
        if maus:
            sys.exit(f"`{condicao}`: em {len(maus)} span(s) o ranking de {pasta.name} não "
                     f"contém todas as notícias do top-5 de evidencias.csv — ex.: {maus[:3]}. É "
                     f"outro corpus, não a mesma query mais funda; não se podem juntar.")
        FUNDO[condicao] = fundo


def lista(pesquisas, leitura):
    """The documents a condition returns for one span under the given configuration."""
    if not pesquisas:
        return []
    if leitura == "primeira_pergunta":
        # Top-5 of the question with the lowest index (the general one in CLEVER).
        primeira = min(pesquisas, key=indice_da_pergunta)
        return [doc for _, doc in pesquisas[primeira]][:CORTE]
    if leitura == "rrf":
        # RRF over the top-5 of every search; ties broken by best (rank, question index),
        # then by doc_id.
        pontos, desempate = defaultdict(float), {}
        for question_id, resultados in pesquisas.items():
            indice = indice_da_pergunta(question_id)
            for rank, doc in resultados[:CORTE]:
                pontos[doc] += 1.0 / (K_RRF + rank)
                if doc not in desempate or (rank, indice) < desempate[doc]:
                    desempate[doc] = (rank, indice)
        return sorted(pontos, key=lambda d: (-pontos[d], desempate[d], d))[:CORTE]
    # "realidade": every distinct doc_id of every search, by best (rank, question index).
    melhor = {}
    for question_id, resultados in pesquisas.items():
        for rank, doc in resultados:
            posicao = (rank, indice_da_pergunta(question_id))
            if doc not in melhor or posicao < melhor[doc]:
                melhor[doc] = posicao
    return [doc for doc, _ in sorted(melhor.items(), key=lambda x: (x[1], x[0]))]


def entrega(dados, condicao, span_id, leitura):
    """What a condition returns for a span (E_i)."""
    pesquisas = dados[condicao].get(span_id, {})
    if leitura == "orcamento_igual":
        # The generated-question conditions keep all their documents; the claim and the
        # claim span descend their own ranking down to B_i.
        if condicao not in FUNDO:
            return lista(pesquisas, "realidade")
        return FUNDO[condicao].get(span_id, [])[:ORCAMENTO.get(span_id, CORTE)]
    return lista(pesquisas, leitura)


def avaliar(dados, gold, chave, leitura):
    """Per condition: micro and macro Recall over relevant and decisive targets, and Docs/span.

    Decisive macro averages only over spans with at least one decisive document.
    """
    saida = {}
    for condicao in dados:
        achados = {"decisivo": 0, "relevante": 0}
        alvo = {"decisivo": 0, "relevante": 0}
        documentos = 0
        macro_rel, macro_dec = [], []
        for span_id, ouro in gold.items():
            entregues = {chave.get(d, d) for d in entrega(dados, condicao, span_id, leitura)}
            documentos += len(entregues)
            esp_rel = {chave.get(d, d) for d in ouro["relevante"]}
            if esp_rel:
                macro_rel.append(len(esp_rel & entregues) / len(esp_rel))
            esp_dec = {chave.get(d, d) for d in ouro["decisivo"]}
            if esp_dec:
                macro_dec.append(len(esp_dec & entregues) / len(esp_dec))
            for tipo in ("decisivo", "relevante"):
                esperados = {chave.get(d, d) for d in ouro[tipo]}
                alvo[tipo] += len(esperados)
                achados[tipo] += len(esperados & entregues)
        saida[condicao] = {
            "recall_decisivo": achados["decisivo"] / alvo["decisivo"] if alvo["decisivo"] else 0,
            "decisivos": achados["decisivo"], "total_decisivos": alvo["decisivo"],
            "recall_relevante": achados["relevante"] / alvo["relevante"] if alvo["relevante"] else 0,
            "relevantes": achados["relevante"], "total_relevantes": alvo["relevante"],
            "docs_por_span": documentos / len(gold) if gold else 0,
            "macro_relevante": sum(macro_rel) / len(macro_rel) if macro_rel else 0.0,
            "macro_decisivo": sum(macro_dec) / len(macro_dec) if macro_dec else 0.0,
        }
    return saida


def por_span(dados, gold, chave, leitura, condicao, tipo):
    """(hits, targets) per claim span, the resampling unit of the bootstrap."""
    saida = []
    for span_id, ouro in gold.items():
        entregues = {chave.get(d, d) for d in entrega(dados, condicao, span_id, leitura)}
        esperados = {chave.get(d, d) for d in ouro[tipo]}
        saida.append((len(esperados & entregues), len(esperados)))
    return saida


def ler_relacoes(dataset, chave):
    """{(span_id, doc key): relation} of every annotated pair (NEI for the irrelevant ones)."""
    relacoes = {}
    for _documento, _item, span_id, span in sorted(iter_claim_spans(ler_clever(dataset)),
                                                   key=lambda x: x[2]):
        for doc in span["retrieved_documents"]:
            doc_id = doc["lusa_doc_id"]
            relacoes[(span_id, chave.get(doc_id, doc_id))] = doc["relation"] or "NEI"
    return relacoes


def veredito_do_conjunto(docs, span_id, relacoes):
    """Supported if some document supports and none refutes, Refuted in the inverse case, else NEI."""
    sup = any(relacoes.get((span_id, d)) == "Supported" for d in docs)
    ref = any(relacoes.get((span_id, d)) == "Refuted" for d in docs)
    if sup and ref:
        return "NEI"
    return "Supported" if sup else "Refuted" if ref else "NEI"


def veracidade(dados, gold, chave, relacoes, leitura):
    """Decisive Claim-Span Coverage.

    The reference status of a span aggregates all its annotated evidence; only spans with a
    single Supported or Refuted status count, and a span is covered when the condition returns
    at least one decisive document with that relation.
    """
    alvo_span, recuperado = {}, {}
    for span_id, ouro in gold.items():
        todos = {chave.get(d, d) for d in ouro["decisivo"] | ouro["relevante"]}
        alvo_span[span_id] = veredito_do_conjunto(todos, span_id, relacoes)
    decidiveis = [s for s, v in alvo_span.items() if v in ("Supported", "Refuted")]
    for condicao in dados:
        certos = 0
        for span_id in decidiveis:
            entregues = {chave.get(d, d) for d in entrega(dados, condicao, span_id, leitura)}
            if veredito_do_conjunto(entregues, span_id, relacoes) == alvo_span[span_id]:
                certos += 1
        recuperado[condicao] = (certos, len(decidiveis))
    return recuperado, alvo_span, decidiveis


def _celulas(r, vr):
    """The table cells of one condition, with numerators and denominators."""
    certos, total = vr
    return [f"{r['macro_relevante']:.1%}",
            f"{r['recall_relevante']:.1%} ({r['relevantes']}/{r['total_relevantes']})",
            f"{r['macro_decisivo']:.1%}",
            f"{r['recall_decisivo']:.1%} ({r['decisivos']}/{r['total_decisivos']})",
            f"{certos / total:.1%} ({certos}/{total})" if total else "—",
            f"{r['docs_por_span']:.1f}"]


COLUNAS = ("Relevant<br>Macro Recall", "Relevant Micro Recall<br>*(hits/total)*",
           "Decisive<br>Macro Recall", "Decisive Micro Recall<br>*(hits/total)*",
           "Decisive Claim-Span<br>Coverage *(n/total)*", "Docs/<br>span")


def tabela_final(dados, gold, chave, relacoes):
    """The three configurations in one table, each sorted by Decisive Micro Recall."""
    linhas = ["## Results", "",
              "| Configuration | Condition | " + " | ".join(COLUNAS) + " |",
              "|---|---|" + "---|" * len(COLUNAS)]
    for leitura, titulo in CONFIGURACOES:
        r = avaliar(dados, gold, chave, leitura)
        vr, _a, _d = veracidade(dados, gold, chave, relacoes, leitura)
        ordem = sorted(dados, key=lambda c: -r[c]["recall_decisivo"])
        for i, condicao in enumerate(ordem):
            etiqueta = titulo if i == 0 else ""
            celulas = _celulas(r[condicao], vr[condicao])
            if leitura != "orcamento_igual":
                celulas[-1] = "—"  # Docs/span only under Matched retrieval volume
            linhas.append(f"| {etiqueta} | {NOMES.get(condicao, condicao)} | "
                          + " | ".join(celulas) + " |")
    return "\n".join(linhas) + "\n"


def escrever(caminho, texto):
    """Write the report atomically (temporary file and rename)."""
    caminho = Path(caminho)
    caminho.parent.mkdir(parents=True, exist_ok=True)
    parcial = caminho.with_name(caminho.name + ".parcial")
    try:
        parcial.write_text(texto, encoding="utf-8")
        os.replace(parcial, caminho)
    except BaseException:
        parcial.unlink(missing_ok=True)
        raise


def caminho_curto(caminho):
    """Path relative to the stage folder or, outside it, to the repository; absolute otherwise."""
    caminho = Path(caminho).resolve()
    for base in (REPO, REPO.parent):
        try:
            return str(caminho.relative_to(base))
        except ValueError:
            continue
    return str(caminho)


def carregar():
    """(dados, gold, chave): searches, reference evidence and reissue equivalence."""
    dados = ler_export()
    spans_do_export = {s for c in dados.values() for s in c}
    gold = ler_gold(spans_do_export)
    todos = {d for c in dados.values() for s in c.values() for p in s.values() for _, d in p}
    todos |= {d for o in gold.values() for tipo in o.values() for d in tipo}
    todos |= {d for c in ler_fundo_bruto().values() for l in c.values() for d in l}
    # The equivalence is computed over every retrieved document, the gold questions' included.
    dados.pop(REFERENCIA, None)
    return dados, gold, equivalencias(todos)


def main():
    argparse.ArgumentParser(description="Evidence retrieval by query strategy.").parse_args()

    dados, gold, chave = carregar()
    preparar_fundo(dados, chave)

    n_dec = sum(len(o["decisivo"]) for o in gold.values())
    n_rel = sum(len(o["relevante"]) for o in gold.values())
    spans_dec = sum(1 for o in gold.values() if o["decisivo"])
    relacoes = ler_relacoes(DATASET, chave)
    _vr, alvo_span, decidiveis = veracidade(dados, gold, chave, relacoes, "orcamento_igual")
    n_contra = sum(1 for sp, v in alvo_span.items() if v == "NEI" and gold[sp]["decisivo"])
    texto = [
        "# Evidence retrieval by query strategy", "",
        "Generated by `src/comparar_queries.py`.", "",
        f"**Reference annotation:** CLEVER evidence annotations — `{caminho_curto(DATASET)}`.", "",
        "## Reference evidence", "",
        f"{len(gold)} claim spans have at least one Relevant reference document "
        f"({n_rel} Relevant pairs); {spans_dec} of them have at least one Supported or "
        f"Refuted document ({n_dec} decisive pairs).",
        f"At claim-span level, {len(decidiveis)} of these {spans_dec} have a single Supported or "
        f"Refuted status and {n_contra} have both Supported and Refuted evidence. DCSC is "
        f"computed over the {len(decidiveis)} claim spans with a single status.", "",
        tabela_final(dados, gold, chave, relacoes),
    ]
    escrever(SAIDA, "\n".join(texto))
    print(caminho_curto(SAIDA))
    print(f"B_i (Matched retrieval volume): mínimo {min(ORCAMENTO.values())}, "
          f"máximo {max(ORCAMENTO.values())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
